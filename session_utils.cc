bool strip_checkpoints_flag(std::string& arg) {
    static const std::string flag = " --checkpoints";
    if (arg.size() >= flag.size() &&
        arg.compare(arg.size() - flag.size(), flag.size(), flag) == 0) {
        arg.erase(arg.size() - flag.size());
        return true;
    }
    return false;
}

