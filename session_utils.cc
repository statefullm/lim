std::string html_escape(const std::string& s) {
    std::string out;
    out.reserve(s.size());
    for (char c : s) {
        if (c == '&') out += "&amp;";
        else if (c == '<') out += "&lt;";
        else if (c == '>') out += "&gt;";
        else if (c == '"') out += "&quot;";
        else out += c;
    }
    return out;
}

std::string html_escape_for_browser(const std::string& s) {
    std::string escaped = html_escape(s);
    size_t pos = 0;
    while ((pos = escaped.find('\n', pos)) != std::string::npos) {
        escaped.replace(pos, 1, "<br>");
        pos += 3;
    }
    return escaped;
}
bool open_session_logs(int idx) {
    string log_file_name = LIM_LOG_DIR + "/" + to_string(idx);
    chat_log.open(log_file_name, ios::app);
    if (!chat_log.is_open()) return false;

    if (is_debug) {
        string token_log_name = LIM_LOG_DIR + "/" + to_string(idx) + ".tokens";
        token_log.open(token_log_name, ios::trunc);
        if (token_log.is_open()) {
            token_log << "# Token Log - Session #" << idx << "\n";
            token_log << "# Format: FEED <label> <token_id> \"<escaped_piece>\"   (tokens fed into context)\n";
            token_log << "#         <seq> <token_id> \"<escaped_piece>\"                     (tokens generated by LLM)\n";
            token_log << "# Escaping: \\n = newline, \\r = carriage return, \\t = tab\n";
        }
    }

    string tps_log_name = LIM_LOG_DIR + "/" + to_string(idx) + ".tps";
    tps_log.open(tps_log_name, ios::trunc);
    if (tps_log.is_open()) {
        tps_log << "# TPS Log - Session #" << idx << "\n";
    }
    return true;
}

void log_tokens(const std::string& label, const std::vector<llama_token>& toks, llama_context* ctx) {
    if (!is_debug || !token_log.is_open()) return;
    for (llama_token t : toks) {
        std::string piece = common_token_to_piece(ctx, t);
        token_log << label << " " << t << " \"" << escape_token_piece(piece) << "\"\n";
    }
    token_log.flush();
}

void strip_tags(std::string& str, const std::vector<std::string>& tags) {
    for (const auto& tag : tags) {
        size_t p;
        while ((p = str.find(tag)) != string::npos) {
            str.erase(p, tag.length());
        }
    }
}

void diag_speed(int n_past, int n_ctx, int t_count, double elapsed, double decode_time) {
    if (t_count <= 0 || elapsed <= 0.0) return;
    double context_percent = (n_past / (double)n_ctx) * 100.0;

    // Pick denominator based on honest_speed global
    double denom = elapsed;  // default: wall clock ("honest")
    if (!honest_speed && decode_time > 0.0) {
        denom = decode_time;
    }

    double speed = t_count / denom;
    int speed_rounded = round_int(speed);

    // Write to TPS log file
    tps_log << n_past << " " << std::fixed << std::setprecision(3) << speed << "\n";

    // Send to browser status bar (compact: no labels)
    if (should_output_to_browser()) {
        std::ostringstream oss2;
        oss2 << speed_rounded << " t/s | " << n_past << " (" << (int)context_percent << "%)";
        stream_speed(oss2.str());
    }
}
