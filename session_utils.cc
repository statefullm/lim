std::string html_escape(const std::string& s) {
  std::string out;
  out.reserve(s.size());
  for (char c : s) {
    if (c == '&') out += "&amp;";
    else if (c == '<') out += "&lt;";
    else if (c == '>') out += "&gt;";
    else if (c == '"') out += "&quot;";
    else out += c;
  }
  return out;
}

std::string html_escape_for_browser(const std::string& s) {
  // Single pass: html_escape plus newline -> <br> (html_escape neither
  // produces nor consumes newlines, so the two fold into one scan).
  std::string out;
  out.reserve(s.size() + s.size() / 16 + 16);
  for (char c : s) {
    if (c == '&') out += "&amp;";
    else if (c == '<') out += "&lt;";
    else if (c == '>') out += "&gt;";
    else if (c == '"') out += "&quot;";
    else if (c == '\n') out += "<br>";
    else out += c;
  }
  return out;
}
int next_free_log_index(int from) {
  if (from < 1) from = 1;
  for (int idx = from; ; idx++) {
    ifstream check(LIM_LOG_DIR + "/" + to_string(idx));
    if (!check.good()) return idx;
  }
}

// Session logs hold the full conversation (file contents, shell output,
// possibly secrets): create them readable only by the owner and the sharing
// group (0660, never others).  Existing files are left untouched.
static void secure_session_log(const string& path) {
  int fd = open(path.c_str(), O_WRONLY | O_CREAT, 0660);
  if (fd < 0) return;  // open_session_logs will report the failure
  close(fd);
}

bool open_session_logs(int idx) {
  string log_file_name = LIM_LOG_DIR + "/" + to_string(idx);
  secure_session_log(log_file_name);
  chat_log.open(log_file_name, ios::app);
  if (!chat_log.is_open()) return false;

  if (is_debug) {
    string token_log_name = LIM_LOG_DIR + "/" + to_string(idx) + ".tokens";
    secure_session_log(token_log_name);
    token_log.open(token_log_name, ios::trunc);
    if (token_log.is_open()) {
      token_log << "# Token Log - Session #" << idx << "\n";
      token_log << "# Format: FEED <label> <token_id> \"<escaped_piece>\"   (tokens fed into context)\n";
      token_log << "#         <seq> <token_id> \"<escaped_piece>\"                     (tokens generated by LLM)\n";
      token_log << "# Escaping: \\n = newline, \\r = carriage return, \\t = tab\n";
    }
  }

  string tps_log_name = LIM_LOG_DIR + "/" + to_string(idx) + ".tps";
  secure_session_log(tps_log_name);
  tps_log.open(tps_log_name, ios::trunc);
  if (tps_log.is_open()) {
    tps_log << "# TPS Log - Session #" << idx << "\n";
  }
  return true;
}

void log_tokens(const std::string& label, const std::vector<llama_token>& toks, llama_context* ctx) {
  if (!is_debug || !token_log.is_open()) return;
  for (llama_token t : toks) {
    std::string piece = common_token_to_piece(ctx, t);
    token_log << label << " " << t << " \"" << escape_token_piece(piece) << "\"\n";
  }
  token_log.flush();
}

void strip_tags(std::string& str, const std::vector<std::string>& tags) {
  for (const auto& tag : tags) {
    // No occurrence: a single find, the old loop's first step, and done.
    if (tag.empty() || str.find(tag) == string::npos) continue;
    // Occurrences present: reduce left-to-right with a stack, O(n) instead
    // of an O(n) erase per occurrence.  The old loop is
    // leftmost-erase-to-fixpoint -- erasing can re-form the tag across the
    // join (tag "ab" over "aabb" yields "ab", then "") -- and the stack
    // catches that re-formation, because the join re-tests on every push
    // and the stack never contains the tag between pushes; a plain forward
    // scan would stop at the first fixpoint and miss it.  The suffix check
    // is gated on the tag's last char, which a match requires.
    const size_t tl = tag.size();
    const char last_c = tag.back();
    string st;
    st.reserve(str.size());
    for (char c : str) {
      st += c;
      if (c == last_c && st.size() >= tl && st.compare(st.size() - tl, tl, tag) == 0) {
        st.resize(st.size() - tl);
      }
    }
    str = std::move(st);
  }
}

void diag_speed(int n_past, int n_ctx, int t_count, double elapsed, double decode_time, bool to_stdout) {
  // t_count <= 1: the sample+sync window contains no decode cycles (it
  // degenerates to clock granularity), so the speed would be meaningless.
  if (t_count <= 1 || elapsed <= 0.0) return;

  // Denominator shared with the mid-generation status bar: the sample+sync
  // window (first to last token) in benchmark mode, else the full wall clock.
  double denom = speed_denominator(elapsed, decode_time);
  double speed = t_count / denom;

  string msg = format_speed_ctx(round_int(speed), n_past, n_ctx);

  // Terminal + chat log: only for the once-per-turn diagnostic printed at
  // the >>> prompt (mid-chain / mid-generation updates are browser-only).
  if (to_stdout) {
    if (should_output_to_stdout()) {
      cout << "\033[35m[" << msg << "]\033[0m\n";
      consoleMarkNewline(true);
    }
    if (chat_log.is_open()) {
      chat_log << "[" << msg << "]" << "\n\n";
      chat_log.flush();
    }
  }

  // Write to TPS log file
  if (denom > 0) {
    tps_log << n_past << " " << std::fixed << std::setprecision(3) << speed << "\n";
  }

  // Send to browser status bar (compact: no labels)
  if (should_output_to_browser()) {
    stream_speed(msg);
  }
}
